/** Uma palavra do dicionário, no idioma ativo (para as regras). */
function W(pt) {
  var hit = (LUME.block && DICT[LUME.block + '|' + pt]) || DICT[pt];
  return hit ? pickLang(hit) : null;
}

var WEEKDAYS = { Seg: ['Mon', 'Lun'], Ter: ['Tue', 'Mar'], Qua: ['Wed', 'Mié'], Qui: ['Thu', 'Jue'], Sex: ['Fri', 'Vie'], 'Sáb': ['Sat', 'Sáb'], Dom: ['Sun', 'Dom'] };
var MONTHS = { jan: ['Jan', 'ene'], fev: ['Feb', 'feb'], mar: ['Mar', 'mar'], abr: ['Apr', 'abr'], mai: ['May', 'may'], jun: ['Jun', 'jun'], jul: ['Jul', 'jul'], ago: ['Aug', 'ago'], set: ['Sep', 'sept'], out: ['Oct', 'oct'], nov: ['Nov', 'nov'], dez: ['Dec', 'dic'] };

RULES.push(
  // heatmap: “Dia 12”, “Seg 9h”
  [/^Dia (\d+)$/, function (m) { return L3('', 'Day ', 'Día ') + m[1]; }],
  [/^(Seg|Ter|Qua|Qui|Sex|Sáb|Dom) (\d+)h$/, function (m) { var d = WEEKDAYS[m[1]]; return L3('', d[0] + ' ' + m[2] + ':00', d[1] + ' ' + m[2] + ' h'); }],
  // datas curtas: “12 de out.”, “de out.”
  [/^(\d+ )?de (jan|fev|mar|abr|mai|jun|jul|ago|set|out|nov|dez)\.?$/, function (m) {
    var mo = MONTHS[m[2]];
    var d = m[1] ? m[1].trim() : '';
    return L3('', mo[0] + (d ? ' ' + d : ''), (d ? d + ' ' : '') + mo[1] + '.');
  }],
  // dimensões: “0.125rem no CSS”, “Duração de 150ms”; sombras: “Sombra xs”
  [/^(.+) no CSS$/, function (m) { return m[1] + L3('', ' in CSS', ' en CSS'); }],
  [/^Duração de (.+)$/, function (m) { return L3('', 'Duration of ', 'Duración de ') + m[1]; }],
  [/^Sombra (\w+)$/, function (m) { return L3('', 'Shadow ', 'Sombra ') + m[1]; }],
  [/^([\d.,]+) mil$/, function (m) { return LANG === 'en' ? enNumbers(m[1]) + 'K' : m[1] + ' mil'; }],
  [/^Lume ([\d.]+)$/, function (m) { return m[0]; }],
  [/^Os mesmos (\d+) ícones do código, como componentes de 24 px\. Arraste uma instância e troque a cor por qualquer variável de texto; nos componentes, use a propriedade “Trocar ícone”\.$/, function (m) {
    return L3('',
      'The same ' + m[1] + ' icons as in code, as 24 px components. Drag an instance and change its color to any text variable; in components, use the “Swap icon” property.',
      'Los mismos ' + m[1] + ' íconos del código, como componentes de 24 px. Arrastra una instancia y cambia el color por cualquier variable de texto; en los componentes, usa la propiedad “Cambiar ícono”.');
  }],
  // valores em real: “R$ 152 mil”, “de R$ 5 mil”, “R$ 1,3 mi”
  [/^(de )?R\$ ([\d.,]+)( mil| mi)?$/, function (m) {
    var de = m[1] ? L3('de ', 'of ', 'de ') : '';
    var unit = m[3] === ' mil' ? L3(' mil', 'K', ' mil') : m[3] === ' mi' ? L3(' mi', 'M', ' M') : '';
    return de + (LANG === 'en' ? 'R$' + enNumbers(m[2]) : 'R$ ' + m[2]) + unit;
  }],
  // “Barra Jan”: rótulo + mês abreviado
  [/^(\D+?) (Jan|Fev|Mar|Abr|Mai|Jun|Jul|Ago|Set|Out|Nov|Dez)$/, function (m) { var w = W(m[1]); var mo = MONTHS[m[2].toLowerCase()]; return w === null ? null : w + ' ' + L3(m[2], mo[0], mo[1].charAt(0).toUpperCase() + mo[1].slice(1)); }],
  // “Neutro quente 25”, “Pedido #4821”, “126 ícones”: o número fica, a palavra vem do dicionário
  [/^(\D+?) (#?[\d.,]+)$/, function (m) { var w = W(m[1]); return w === null ? null : w + ' ' + (LANG === 'en' ? enNumbers(m[2]) : m[2]); }],
  [/^([\d.,]+) (\D+)$/, function (m) { var w = W(m[2]); return w === null ? null : (LANG === 'en' ? enNumbers(m[1]) : m[1]) + ' ' + w; }],
  // item de legenda: “· Grátis”
  [/^· (.+)$/, function (m) { return '· ' + L(m[1]); }],
  // camadas com prefixo: “Barra Norte”, “Etapa Visitaram”, “Fatia Pix”
  [/^(Barra|Etapa|Rótulo|Fatia|Ponto|Linha|Bolha|Série|Coluna|Célula|Segmento|Valor|Item) (.+)$/, function (m) { var w = W(m[1]); return w === null ? null : w + ' ' + L(m[2]); }],
  // nome de componente com grupo: “App shell/Miniatura”, “Menu/Separador”
  [/^[^/\s](?:[^/]*[^/\s])?(\/[^/\s](?:[^/]*[^/\s])?)+$/, function (m) { return m[0].split('/').map(function (p) { return L(p); }).join('/'); }]
);

